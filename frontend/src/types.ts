export type Usage = { cpu: number; memory: number; timestamp: string };
export type Container = {
  name: string;
  id: string;
  image: string;
  ready: boolean;
  restarts: number;
  state: string;
  cpuRequest: number;
  cpuLimit: number;
  memoryRequest: number;
  memoryLimit: number;
  usage: Usage | null;
};
export type Resource = {
  deletedAt?: string;
  uid: string;
  kind: string;
  name: string;
  namespace: string;
  created: string;
  labels: Record<string, string>;
  ownerUid: string;
  workloadUid: string;
  status: string;
  ready: number;
  desired: number;
  restarts: number;
  node: string;
  containers: Container[];
  related: string[];
  usage: Usage | null;
  cpuCapacity: number;
  memoryCapacity: number;
  cpuAllocatable: number;
  memoryAllocatable: number;
  capacity: number;
  provisioner?: string;
  storageClass: string;
  volume: string;
  accessModes: string[];
  conditions: string[];
};
export type KEvent = {
  uid: string;
  resourceUid: string;
  namespace: string;
  name: string;
  reason: string;
  message: string;
  type: string;
  count: number;
  timestamp: string;
};
export type Snapshot = {
  cluster: string;
  timestamp: string;
  connected: boolean;
  connectionError: string;
  sources: { kind: string; synced: boolean; error: string }[];
  metrics: { available: boolean; error: string; lastSuccess: string };
  resources: Resource[];
  deletedResources: Resource[];
  events: KEvent[];
  truncated: boolean;
  historyDropped: number;
};
export type Point = {
  uid: string;
  cpu: number;
  memory: number;
  timestamp: string;
};
export type LogResult = {
  text: string;
  timestamp: string;
  source: string;
  truncated: boolean;
  persisted: boolean;
  maxLines: number;
  maxBytes: number;
};
